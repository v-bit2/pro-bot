const pieTypes = [
  "Apple Pie 🥧",
  "Cherry Pie 🍒",
  "Pumpkin Pie 🎃",
  "Pecan Pie 🌰",
  "Key Lime Pie 🍋",
  "Blueberry Pie 🫐"
];

export const command = {
  name: "pies",
  category: "FUN",
  description: "Get a delicious random pie",
  usage: ".pies",
  async execute({ sock, message }) {
    const pie = pieTypes[Math.floor(Math.random() * pieTypes.length)];
    await sock.sendMessage(message.key.remoteJid, { text: `${pie}\n\n> Generated By Voltra` }, { quoted: message });
  }
};
