export const command = {
  name: "bomb",
  category: "FUN",
  description: "Plant a fun countdown bomb in the chat",
  usage: ".bomb",
  async execute({ sock, message }) {
    await sock.sendMessage(message.key.remoteJid, { text: "3... 2... 1... 💥 BOOM!\n\n> Generated By Voltra" }, { quoted: message });
  }
};
