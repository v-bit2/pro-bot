const jokes = [
  "Why do programmers prefer dark mode? Because light attracts bugs!",
  "There are 10 types of people in the world: Those who understand binary, and those who don't.",
  "Why did the JavaScript developer wear glasses? Because he didn't C#!",
  "A SQL query walks into a bar, walks up to two tables and asks: 'Can I join you?'"
];

export const command = {
  name: "joke",
  aliases: ["randomjoke"],
  category: "FUN",
  description: "Get a random funny joke",
  usage: ".joke",
  async execute({ sock, message }) {
    let jokeText = "";
    try {
      const res = await fetch("https://official-joke-api.appspot.com/random_jokes");
      if (res.ok) {
        const data = await res.json();
        jokeText = `${data.setup}\n\n${data.punchline}`;
      }
    } catch {}

    if (!jokeText) {
      jokeText = jokes[Math.floor(Math.random() * jokes.length)];
    }

    await sock.sendMessage(message.key.remoteJid, { text: `${jokeText}\n\n> Generated By Voltra` }, { quoted: message });
  }
};
