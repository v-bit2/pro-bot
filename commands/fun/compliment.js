const compliments = [
  "You're a ray of sunshine on a cloudy day!",
  "Your smile is infectious!",
  "You're smarter than Google!",
  "You bring out the best in everyone around you!"
];

export const command = {
  name: "compliment",
  category: "FUN",
  description: "Send a sweet compliment to yourself or a friend",
  usage: ".compliment [@user]",
  async execute({ sock, message }) {
    const comp = compliments[Math.floor(Math.random() * compliments.length)];
    await sock.sendMessage(message.key.remoteJid, { text: `${comp}\n\n> Generated By Voltra` }, { quoted: message });
  }
};
